// Concatenates src/*.gs into dist/Code.gs: a single file people can paste into the
// Apps Script editor without clasp. Config.gs goes first because other files read its
// constants at load time.
import { readdirSync, readFileSync, mkdirSync, writeFileSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'src';
const OUT = 'dist';
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));

const files = readdirSync(SRC)
  .filter(f => f.endsWith('.gs'))
  .sort((a, b) => (a === 'Config.gs' ? -1 : b === 'Config.gs' ? 1 : a.localeCompare(b)));

const header = `// Trackex v${pkg.version} — ${pkg.homepage}\n// Generated by scripts/bundle.mjs from src/. Do not edit; edit src/ instead.\n\n`;
const body = files.map(f => `// ===== ${f} =====\n${readFileSync(join(SRC, f), 'utf8').trimEnd()}\n`).join('\n');

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'Code.gs'), header + body);
copyFileSync(join(SRC, 'Dashboard.html'), join(OUT, 'Dashboard.html'));
copyFileSync(join(SRC, 'appsscript.json'), join(OUT, 'appsscript.json'));
console.log(`dist/Code.gs: ${files.length} files → ${(header + body).length} chars`);
